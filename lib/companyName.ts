// Сокращение организационно-правовых форм в названиях компаний
// "Товарищество с ограниченной ответственностью «Название»" → ТОО «Название»
export function shortCompanyName(name: string): string {
  if (!name) return '';
  let s = name.trim();
  const replacements: [RegExp, string][] = [
    [/товарищество\s+с\s+ограниченной\s+ответственностью/gi, 'ТОО'],
    [/индивидуальный\s+предприниматель/gi, 'ИП'],
    [/акционерное\s+общество/gi, 'АО'],
    [/открытое\s+акционерное\s+общество/gi, 'ОАО'],
    [/закрытое\s+акционерное\s+общество/gi, 'ЗАО'],
    [/государственное\s+учреждение/gi, 'ГУ'],
    [/производственный\s+кооператив/gi, 'ПК'],
    [/крестьянское\s+хозяйство/gi, 'КХ'],
    [/общественное\s+объединение/gi, 'ОО'],
    [/некоммерческое\s+акционерное\s+общество/gi, 'НАО'],
  ];
  for (const [re, abbr] of replacements) s = s.replace(re, abbr);
  return s.replace(/\s+/g, ' ').trim();
}
